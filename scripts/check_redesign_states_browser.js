async page => {
  // Fault injection is confined to this browser test; product data is untouched.
  const fixture = await (await fetch('http://127.0.0.1:8765/chart-fixture.json')).json();
  const errors = [];
  const onError = error => errors.push(error.message);
  page.on('pageerror', onError);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:8081/#question');
  await page.route('**/api/demo-finance/question', route => route.fulfill({ status: 503, json: { detail: 'سرویس مدل موقتاً در دسترس نیست.' } }));
  await page.getByLabel('پرسش فارسی', { exact: true }).fill('آزمون خطا');
  await page.getByRole('button', { name: 'تحلیل پرسش', exact: true }).click();
  await page.getByText('پاسخ دریافت نشد', { exact: true }).waitFor();
  await page.screenshot({ path: 'artifacts/after-error-mobile.png', fullPage: true });
  await page.unroute('**/api/demo-finance/question');
  await page.route('**/api/demo-finance/question', route => route.fulfill({ json: fixture.pages[0] }));
  await page.getByRole('button', { name: 'تلاش دوباره', exact: true }).click();
  await page.locator('.question-answer').waitFor();
  await page.unroute('**/api/demo-finance/question');
  const unavailable = { ...fixture.pages[0], status: 'data_unavailable', spec: null, message: 'دادهٔ کافی برای این پرسش موجود نیست.', limitations: ['این سنجه در داده‌های دمو ثبت نشده است.'] };
  await page.route('**/api/demo-finance/question', route => route.fulfill({ json: unavailable }));
  await page.getByLabel('پرسش فارسی', { exact: true }).fill('آزمون دادهٔ ناکافی');
  await page.getByRole('button', { name: 'تحلیل پرسش', exact: true }).click();
  await page.getByText('دادهٔ کافی در دسترس نیست', { exact: true }).waitFor();
  await page.screenshot({ path: 'artifacts/after-unavailable-mobile.png', fullPage: true });
  await page.unroute('**/api/demo-finance/question');
  let release;
  const blocked = new Promise(resolve => { release = resolve; });
  await page.route('**/api/demo-finance/question', async route => { await blocked; await route.fulfill({ json: fixture.pages[0] }).catch(() => {}); });
  await page.getByLabel('پرسش فارسی', { exact: true }).fill('آزمون لغو');
  await page.getByRole('button', { name: 'تحلیل پرسش', exact: true }).click();
  await page.getByRole('button', { name: 'لغو درخواست', exact: true }).click();
  release();
  await page.locator('.generation-state').waitFor({ state: 'detached' });
  if (await page.getByLabel('پرسش فارسی', { exact: true }).inputValue() !== 'آزمون لغو') throw new Error('Cancelled question should remain editable');
  await page.unroute('**/api/demo-finance/question');
  await page.goto('http://127.0.0.1:8081/');
  await page.locator('.preview-metric').first().waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(400);
  const before = await page.locator('.beam-core').evaluate(node => getComputedStyle(node).opacity);
  await page.waitForTimeout(1200);
  const after = await page.locator('.beam-core').evaluate(node => getComputedStyle(node).opacity);
  if (Math.abs(Number(before) - Number(after)) < .005) throw new Error('Beam should change gently over time');
  await page.screenshot({ path: 'artifacts/after-landing-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'شروع', exact: true }).hover();
  await page.waitForTimeout(300);
  const hover = await page.getByRole('button', { name: 'شروع', exact: true }).evaluate(node => getComputedStyle(node).transform);
  await page.getByRole('button', { name: 'شروع', exact: true }).screenshot({ path: 'artifacts/after-start-hover.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const reduced = await page.locator('.beam-core').evaluate(node => ({ animation: getComputedStyle(node).animationName, transform: getComputedStyle(node).transform }));
  if (reduced.animation !== 'none') throw new Error('Beam must stop in reduced-motion mode');
  await page.keyboard.press('Tab');
  await page.getByRole('button', { name: 'شروع', exact: true }).focus();
  const focus = await page.getByRole('button', { name: 'شروع', exact: true }).evaluate(node => ({ visible: node.matches(':focus-visible'), outline: getComputedStyle(node).outlineStyle }));
  await page.keyboard.press('Enter');
  await page.locator('.chat-panel').waitFor();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow || errors.length || focus.outline === 'none') throw new Error(JSON.stringify({ overflow, errors, focus }));
  await page.screenshot({ path: 'artifacts/after-reduced-mobile.png', fullPage: true });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  page.off('pageerror', onError);
  return { errorRetry: 'passed', unavailable: 'passed', cancel: 'passed', beamOpacity: [before, after], reduced, hover, focus, overflow, pageErrors: errors };
}
